"""Optional local-only ASR adapters. Model downloads are a separate explicit setup step."""
from pathlib import Path
from .acoustic import read_pcm


def transcribe(raw, engine, model_path, language=None, device="cpu"):
    samples = read_pcm(raw)
    if not samples:
        raise ValueError("音频为空")
    path = Path(model_path)
    if not path.is_dir():
        raise ValueError(f"模型尚未下载：{path.name}。请运行 setup-ai.ps1，或参考 docs/AUDIO_ALIGNMENT.md")
    # numpy 只在这两个可选识别引擎里用；程序本身 `dependencies = []`，
    # 正常运行（导入歌词、波形编辑、智能贴唱、导出）一个三方依赖都不需要。
    # 所以缺了它必须给出**可读的中文原因**：`ModuleNotFoundError` 不是 `ValueError`，
    # 服务端会把它落到 500「服务器内部错误」，用户看不出该做什么。
    try:
        import numpy as np
    except ImportError as exc:
        raise ValueError("缺少 numpy（可选识别依赖）：请先运行 setup-ai.ps1，"
                         "或参考 docs/AUDIO_ALIGNMENT.md") from exc
    audio = np.asarray(samples, dtype=np.float32) / 32768
    duration = len(samples) * 1000 // 16000
    if engine == "faster-whisper":
        try:
            from faster_whisper import WhisperModel
        except ImportError as exc:
            raise ValueError("缺少 faster-whisper，请先运行 setup-ai.ps1") from exc
        model = WhisperModel(str(path), device=device,
                             compute_type="int8" if device == "cpu" else "float16",
                             local_files_only=True, cpu_threads=4)
        segments, info = model.transcribe(audio, language=language or None, beam_size=3,
                                          word_timestamps=True, vad_filter=False,
                                          condition_on_previous_text=False)
        chunks = []
        for segment in segments:
            if segment.no_speech_prob > .8:
                continue
            for word in segment.words or []:
                if word.end > word.start:
                    chunks.append({"start": word.start, "end": word.end, "text": word.word})
        return {"engine": engine, "language": info.language,
                "language_probability": info.language_probability,
                "duration_ms": duration, "segments": chunks}
    if engine == "heart-transcriptor":
        try:
            import torch
            from transformers import WhisperForConditionalGeneration, WhisperProcessor, pipeline
        except ImportError as exc:
            raise ValueError("HeartTranscriptor 需要安装 .[heart] 依赖和本地模型") from exc
        dtype = torch.float32 if device == "cpu" else torch.float16
        model = WhisperForConditionalGeneration.from_pretrained(str(path), torch_dtype=dtype,
                                                                 local_files_only=True, attn_implementation="eager")
        processor = WhisperProcessor.from_pretrained(str(path), local_files_only=True)
        # HeartTranscriptor uses the standard Whisper architecture. Word times are derived
        # by Transformers' cross-attention/DTW pipeline, not generated by text interpolation.
        pipe = pipeline("automatic-speech-recognition", model=model, tokenizer=processor.tokenizer,
                        feature_extractor=processor.feature_extractor, device=-1 if device == "cpu" else 0,
                        torch_dtype=dtype, chunk_length_s=30, batch_size=1)
        kwargs = {"task": "transcribe", "num_beams": 1, "condition_on_prev_tokens": False}
        if language:
            kwargs["language"] = language
        with torch.inference_mode():
            result = pipe({"raw": audio, "sampling_rate": 16000}, return_timestamps="word", generate_kwargs=kwargs)
        chunks = []
        for item in result.get("chunks", []):
            start, end = item.get("timestamp", (None, None))
            if start is not None and end is not None and end > start:
                chunks.append({"start": start, "end": end, "text": item["text"]})
        if not chunks:
            raise ValueError("HeartTranscriptor 未返回有效逐词时间，请检查模型的 alignment_heads 配置及音频")
        from .language import detect
        return {"engine": engine, "language": language or detect(result.get("text", ""))["code"],
                "duration_ms": duration, "segments": chunks}
    raise ValueError("未知识别引擎")
